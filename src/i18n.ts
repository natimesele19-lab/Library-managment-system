export function applyTextOverrides(english: Record<string, string>, amharic: Record<string, string>) {
  i18n.removeResourceBundle("en", "translation");
  i18n.removeResourceBundle("am", "translation");
  i18n.addResourceBundle("en", "translation", { ...en, ...english });
  i18n.addResourceBundle("am", "translation", { ...am, ...amharic });
}

i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, am: { translation: am } },
  lng: localStorage.getItem("library-language") || "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

i18n.on("languageChanged", (language) => localStorage.setItem("library-language", language));

export default i18n;
